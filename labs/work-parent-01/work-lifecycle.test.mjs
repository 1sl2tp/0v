import {roleFor,parentState,applyEvent,planBatch,prepareQuestion,linkProjection} from './work-lifecycle.mjs';
const base={"id":"w1","scope":"demo","conversationId":"c1","role":"customer","intentKey":"sale-1","revision":0,"events":[],"lines":[{"key":"A","qty":6},{"key":"B","qty":20},{"key":"C","qty":3},{"key":"D","qty":5}]};
const evt={"scope":"demo","conversationId":"c1","role":"customer","intentKey":"sale-1","eventId":"m1","sourceRevision":1,"expectedRevision":0,"op":"repeat","lines":[{"key":"A","qty":6},{"key":"B","qty":20},{"key":"C","qty":3},{"key":"D","qty":5}]};
let checks=0;
function check(v){if(!v)throw Error("local contract check "+checks);checks++}
check(roleFor({id:"c",group:"customer"},[])==="customer");
check(roleFor({id:"a",group:"other"},["a"])==="supplier");
check(roleFor({id:"e",group:"other"},["a"])==="unresolved");
check(roleFor({id:"a",group:"customer"},["a"])==="unresolved");
check(parentState([{state:"done",proof:"ack"},{state:"need"}])==="need");
check(parentState([{state:"done"}])==="need");
check(parentState([{state:"done",proof:"ack"}])==="done");
check(parentState([{state:"active"},{state:"new"}])==="active");
check(parentState([])==="new");
const a=applyEvent(base,evt);
check(a.state.lines.reduce((n,l)=>n+l.qty,0)===34);
check(applyEvent(a.state,evt).status==="replay");
check(applyEvent(a.state,{...evt,sourceRevision:2}).status==="source_edit_review");
check(applyEvent(a.state,{...evt,eventId:"m2",expectedRevision:0}).status==="stale");
check(applyEvent(base,{...evt,role:"supplier"}).status==="scope_or_role");
check(applyEvent(base,{...evt,intentKey:"sale-2"}).status==="separate_work");
check(applyEvent(base,{...evt,op:"add",lines:[{key:"A",qty:2}]}).state.lines[0].qty===8);
check(applyEvent(base,{...evt,op:"replace",lines:[{key:"A",qty:2}]}).state.lines[0].qty===2);
check(applyEvent(base,{...evt,op:"remove",lines:[{key:"A",qty:6}]}).state.lines.length===3);
check(applyEvent(base,{...evt,op:"repeat",lines:[{key:"A",qty:9}]}).status==="review");
check(planBatch({lastAt:0,now:299999,deltaIds:["m"],processedIds:[]}).length===0);
check(planBatch({lastAt:0,now:300000,deltaIds:["m","m","n"],processedIds:["n"]}).length===1);
check(planBatch({lastAt:0,now:300000,deltaIds:["m"],processedIds:[],inFlight:true}).length===0);
check(prepareQuestion(base," hỏi ").sent===false);
check(linkProjection(base,{scope:"demo",conversationId:"c1",kind:"ledger",id:"l1",verified:false}).status==="review");
const linked=linkProjection(base,{scope:"demo",conversationId:"c1",kind:"ledger",id:"l1",verified:true});
check(linked.status==="linked");
check(linkProjection(linked.card,{scope:"demo",conversationId:"c1",kind:"ledger",id:"l1",verified:true}).status==="replay");
console.log("WORK-PARENT-01 "+checks+" synthetic checks passed");
